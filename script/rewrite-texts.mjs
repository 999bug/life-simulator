function main() {
  const path = new URL('./chiled.json', import.meta.url);
  const events = JSON.parse(readFileSync(path, 'utf8'));
  let n = 0;
  for (const e of events) {
    if (T[e.id]) {
      e.text = T[e.id];
      n++;
    }
  }
  writeFileSync(path, JSON.stringify(events, null, 2), 'utf8');
  console.log(`✅ 补写 ${n} 个事件文本`);

  // 校验补写文本长度
  const out = Object.values(T).filter(t => t.length < 50 || t.length > 150);
  console.log(out.length ? `⚠️ 超范围: ${out.map(t => t.length).join(', ')}` : '✅ 全部在 50-150 字');
}

main();
